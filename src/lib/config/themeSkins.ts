export type SkinPaletteKey = keyof typeof SKIN_PALETTES;

export interface SkinTokens {
	id: SkinPaletteKey;
	valor: string;
	grupo: string;
	label: string;
	etiqueta: string;
	gradient: string;
	bgMain: string;
	bgCard: string;
	bgBase: string;
	bgGradient: string;
	glassBg: string;
	glassBorder: string;
	primary: string;
	secondary: string;
	accent: string;
	textMain: string;
	textMuted: string;
	glow: string;
	fontHeading: string;
	fontBody: string;
	badgeBg: string;
	badgeBorder: string;
}

interface SkinMeta {
	id: SkinPaletteKey;
	valor: string;
	grupo: string;
	secondary: string;
	bgTop: string;
	textMain?: string;
	textMuted?: string;
	badgeBg?: string;
	badgeBorder?: string;
}

/** Construye la configuración completa de un skin combinando su paleta maestra y metadatos UI. */
function buildSkinTokens(meta: SkinMeta): SkinTokens {
	const palette = SKIN_PALETTES[meta.id];
	return {
		id: meta.id,
		valor: meta.valor,
		grupo: meta.grupo,
		label: palette.label,
		etiqueta: palette.label,
		gradient: palette.gradient,
		bgMain: palette.bgMain,
		bgCard: palette.bgCard,
		bgBase: palette.bgMain,
		bgGradient: `radial-gradient(circle at top right, ${meta.bgTop} 0%, ${palette.bgMain} 100%)`,
		glassBg: palette.bgCard,
		glassBorder: `color-mix(in srgb, ${palette.accent} 28%, transparent)`,
		primary: palette.accent,
		secondary: meta.secondary,
		accent: palette.accent,
		textMain: meta.textMain ?? '#f1f5f9',
		textMuted: meta.textMuted ?? '#94a3b8',
		glow: palette.glow,
		fontHeading: palette.fontHeading,
		fontBody: palette.fontBody,
		badgeBg:
			meta.badgeBg ??
			`linear-gradient(135deg, color-mix(in srgb, ${palette.accent} 22%, rgba(10, 14, 20, 0.88)) 0%, color-mix(in srgb, ${meta.secondary} 26%, rgba(10, 14, 20, 0.92)) 100%)`,
		badgeBorder:
			meta.badgeBorder ?? `color-mix(in srgb, ${palette.accent} 58%, ${meta.secondary})`
	};
}

